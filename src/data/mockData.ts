export function inferGenderFromName(name: string): PersonGender {
  const norm = name.trim().toLowerCase();
  for (const entry of CANONICAL_PORTRAIT_BY_KEYWORD) {
    if (entry.keywords.some((kw) => norm.includes(kw))) {
      return entry.gender;
    }
  }
  return 'male';
}

export function resolveGenderMatchedAvatar(
  name: string,
  currentAvatar?: string,
  preferredGender?: PersonGender
): string {
  const norm = (name || '').trim().toLowerCase();
  const gender = preferredGender || inferGenderFromName(norm);
  const matchingPool = gender === 'female' ? FEMALE_PORTRAITS : MALE_PORTRAITS;
  const oppositePool = gender === 'female' ? MALE_PORTRAITS : FEMALE_PORTRAITS;

  // Canonical exact match always wins if currentAvatar is broken, Unsplash, raw /src path, or wrong gender
  const canonical = CANONICAL_PORTRAIT_BY_KEYWORD.find((entry) =>
    entry.keywords.some((kw) => norm.includes(kw))
  );

  const isLegacyOrExternal =
    !currentAvatar ||
    currentAvatar.trim() === '' ||
    currentAvatar.startsWith('/src/assets/') ||
    currentAvatar.includes('images.unsplash.com/photo-');

  const isWrongGender = Boolean(currentAvatar && oppositePool.includes(currentAvatar));

  if (!isLegacyOrExternal && !isWrongGender) {
    // Even if valid local asset, keep canonical person portrait consistent across all views
    if (canonical && currentAvatar !== canonical.avatar && !matchingPool.includes(currentAvatar!)) {
      return canonical.avatar;
    }
    if (canonical && (norm.includes('anna') || norm.includes('jennies') || norm.includes('elena') || norm.includes('hiroshi') || norm.includes('alexander') || norm.includes('classie') || norm.includes('george') || norm.includes('mac') || norm.includes('liam') || norm.includes('priya') || norm.includes('marcus') || norm.includes('astrid'))) {
      return canonical.avatar;
    }
    return currentAvatar!;
  }

  if (canonical) {
    return canonical.avatar;
  }

  let hash = 0;
  for (let i = 0; i < norm.length; i++) {
    hash = (hash << 5) - hash + norm.charCodeAt(i);
    hash |= 0;
  }
  return matchingPool[Math.abs(hash) % matchingPool.length];
}


